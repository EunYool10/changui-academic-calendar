-- Run once in the Supabase SQL editor. Then promote approved staff accounts below.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('viewer','teacher','admin'))
);

create table if not exists public.school_events (
  id bigint generated by default as identity primary key,
  start_date date not null,
  end_date date not null,
  title text not null check (char_length(title) between 1 and 100),
  category text not null default 'school' check (category in ('school','exam','holiday')),
  created_at timestamptz not null default now(),
  constraint school_events_valid_dates check (end_date >= start_date)
);

alter table public.profiles enable row level security;
alter table public.school_events enable row level security;

create or replace function public.current_staff_role()
returns text language sql stable security definer set search_path = ''
as $$ select role from public.profiles where id = (select auth.uid()) $$;

create or replace function public.create_default_profile()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, role) values (new.id, 'viewer')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.create_default_profile();

drop policy if exists "profile read own" on public.profiles;
create policy "profile read own" on public.profiles for select to authenticated
  using (id = (select auth.uid()));

drop policy if exists "events visible to everyone" on public.school_events;
create policy "events visible to everyone" on public.school_events for select to anon, authenticated using (true);

drop policy if exists "staff add events" on public.school_events;
create policy "staff add events" on public.school_events for insert to authenticated
  with check (public.current_staff_role() in ('teacher','admin'));

drop policy if exists "staff edit events" on public.school_events;
create policy "staff edit events" on public.school_events for update to authenticated
  using (public.current_staff_role() in ('teacher','admin'))
  with check (public.current_staff_role() in ('teacher','admin'));

drop policy if exists "staff delete events" on public.school_events;
create policy "staff delete events" on public.school_events for delete to authenticated
  using (public.current_staff_role() in ('teacher','admin'));

